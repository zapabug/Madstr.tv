// The RSS proxy as pleb.world functions (spec feat-plebworld-deploy §D2): plain ESM JS, as pleb.world's rules
// ask, generated from server/rssProxy.ts so there is one source. Written to dist-pleb-api/, which
// scripts/deploy-pleb.sh copies to pleb.world's api/.
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { transformWithEsbuild } from 'vite';

const out = 'dist-pleb-api';
mkdirSync(`${out}/_lib`, { recursive: true });
const proxy = await transformWithEsbuild(readFileSync('server/rssProxy.ts', 'utf8'), 'rssProxy.ts', { loader: 'ts', format: 'esm', target: 'node22' });
writeFileSync(`${out}/_lib/rssProxy.js`, `// Generated from Madstr.tv server/rssProxy.ts by scripts/build-pleb-api.mjs. Do not edit here.\n${proxy.code}`);
writeFileSync(`${out}/rss.js`, `// Generated by Madstr.tv scripts/build-pleb-api.mjs. Do not edit here.
// GET /api/rss?url=... : same-origin RSS proxy for Mad⚡tr.tv at /madstr/ (feeds that refuse cross-origin reads).
import { handleRssRequest } from './_lib/rssProxy.js';

export async function GET(request) {
  const feedUrl = new URL(request.url).searchParams.get('url');
  const result = await handleRssRequest(feedUrl);
  const body = typeof result.body === 'string' ? result.body : new Uint8Array(result.body);
  return new Response(body, { status: result.status, headers: result.headers });
}
`);
console.log(`[build-pleb-api] wrote ${out}/rss.js and ${out}/_lib/rssProxy.js`);
